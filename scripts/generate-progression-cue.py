"""Historical original reward cue; retired from playback in favor of the ending bell.

Kept for provenance. Regeneration writes an ignored development master, never a
runtime asset. Current sounds are generated by generate-meditation-sounds.py.
"""
import wave, struct, math
from pathlib import Path
output = Path(__file__).resolve().parent.parent / '.expo' / 'sound' / 'masters' / 'progression-swell.wav'
output.parent.mkdir(parents=True, exist_ok=True)
rate, seconds = 22050, 7
with wave.open(str(output),'wb') as wav:
    wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(rate)
    frames=bytearray()
    for i in range(rate*seconds):
        t=i/rate
        envelope=(1-math.exp(-t/0.35))*math.exp(-t/1.8)*(math.cos(math.pi*t/(2*seconds))**2)
        signal=.28*math.sin(2*math.pi*196*t)+.12*math.sin(2*math.pi*294*t)+.07*math.sin(2*math.pi*392*t)
        frames+=struct.pack('<h',round(32767*signal*envelope))
    wav.writeframes(frames)
